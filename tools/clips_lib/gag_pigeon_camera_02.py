def pigeon(pose='stand', peck=0, step=0):
    """Assemble + outline once per pose; returns (sprite, anchor offset x, y). Feet at the sprite's bottom."""
    wing = {'stand': WING_MID, 'fly_up': WING_UP, 'fly_down': WING_DOWN}[pose]
    parts = [(BODY, 3, 10), (TAIL, 22, 6), (wing, 6, 9 + (0 if pose == 'stand' else (-3 if pose == 'fly_up' else 2)))]
    parts.append((HEAD, 0 + peck * 1, 0 - peck * 4))   # peck UP into the notch underside
    if pose == 'stand': parts.append((LEG_A if step == 0 else LEG_B, 10, 25))
    spr, mx, my = assemble(parts)
    return outline(spr), mx, my

def build():
    c = Clip('gag_pigeon_camera_02', 5.0)
    land_x, land_y = NOTCH_R - 36, H - 32           # stands under the notch's right half, head reaches its underside
    for i in range(c.n):
        im = c.frame()
        if i < 16:                                   # fly in from the right, descend
            t = ease(i / 15)
            x = (W + 8) + (land_x - (W + 8)) * t; y = 4 + (land_y - 4) * t
            spr, mx, my = pigeon('fly_up' if (i // 3) % 2 == 0 else 'fly_down'); c.blit(im, spr, x + mx, y + my)
            if i == 15: puff(im, land_x + 14, H - 1, 0.1)
        elif i < 44:                                 # peck cycle at the notch underside: 4 up, 3 down
            j = (i - 16) % 7; pk = 1 if j >= 4 else 0
            spr, mx, my = pigeon('stand', peck=pk); c.blit(im, spr, land_x + mx, land_y + my + bob(i, 24, 1))
            shadow(im, land_x + 6, 26)
        elif i < 48:                                 # look at the viewer
            spr, mx, my = pigeon('stand'); c.blit(im, spr, land_x + mx, land_y + my); shadow(im, land_x + 6, 26)
        else:                                        # fly off up-right
            t = ease((i - 48) / 11)
            x = land_x + ((W + 20) - land_x) * t; y = land_y + (-30 - land_y) * t
            spr, mx, my = pigeon('fly_up' if (i // 3) % 2 == 0 else 'fly_down'); c.blit(im, spr, x + mx, y + my)
            if i == 48: puff(im, land_x + 14, H - 1, 0.2)
    return c
